// operator arimatika
// + -> a + b
// - -> a-b
// * -> a * b
// / -> a / b
// % -> a % b
package main

import "fmt"

func main() {
	var a, b int = 10, 3
	fmt.Println("nilai a + b adalah ", a+b)
	fmt.Println("nilai a - b adalah ", a-b)
	fmt.Println("nilai a * b adalah ", a*b)
	fmt.Println("nilai a / b adalah ", a/b)
	fmt.Println("nilai a % b adalah ", a%b)
}
